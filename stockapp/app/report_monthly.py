import os
from datetime import datetime
from pathlib import Path
from typing import List, Dict, Any
import pandas as pd
from stockapp.app.settings import settings
from stockapp.app.longterm import evaluate_long_term_candidates
from stockapp.app.log import logger

def generate_monthly_report(offline_mode: bool = False) -> Path:
    """Generates the Monthly Long-Term Quality Compounder Report."""
    candidates = evaluate_long_term_candidates(offline_mode=offline_mode)
    month_str = datetime.now().strftime("%Y_%m")
    settings.reports_dir.mkdir(parents=True, exist_ok=True)
    report_file = settings.reports_dir / f"monthly_longterm_{month_str}.md"

    with open(report_file, "w", encoding="utf-8") as f:
        f.write(f"# Monthly Long-Term Compounder Dossier ({datetime.now().strftime('%B %Y')})\n\n")
        f.write("### 6-Rule Quality Gate Criteria:\n")
        f.write("- **ROCE 5-Yr Avg:** >= 15% (No single year < 10%)\n")
        f.write("- **3-Yr Sales Growth:** >= 10%\n")
        f.write("- **3-Yr PAT Growth:** >= 10%\n")
        f.write("- **Debt / Equity:** <= 0.50 (Zero or low debt)\n")
        f.write("- **Cash Conversion:** CFO >= 70% of PAT\n")
        f.write("- **Timing Rule:** Accumulate in 3 parts over 3 months on dips inside primary uptrend\n\n")

        f.write("## Qualified Long-Term Candidates\n\n")
        f.write("| Symbol | Quality Pass | Score (/100) | 5-Yr ROCE | 3-Yr Sales Gr | 3-Yr PAT Gr | D/E | CFO/PAT | Action |\n")
        f.write("|---|---|---|---|---|---|---|---|---|\n")

        # Sort by total score descending
        sorted_cand = sorted(candidates, key=lambda x: x["score_total"], reverse=True)
        for c in sorted_cand:
            pass_str = "PASSED" if c["quality_pass"] else "FAILED"
            f.write(f"| **{c['symbol']}** | {pass_str} | {c['score_total']} | {c['roce_5yr_avg']:.1f}% | {c['sales_growth_3yr']:.1f}% | {c['profit_growth_3yr']:.1f}% | {c['debt_equity']:.2f} | {c['cfo_to_pat']*100:.0f}% | **{c['tranche_timing']}** |\n")

        f.write("\n\n*Generated by Stock App v4 Long-Term Engine.*\n")

    logger.info(f"Generated monthly report at {report_file}")
    return report_file

if __name__ == "__main__":
    generate_monthly_report(offline_mode=True)
